#!/bin/sh
set -e

echo "⚠️ ОТКАТ К ПРЕДЫДУЩЕЙ ВЕРСИИ"
echo "============================"
echo "Текущий коммит: $(git rev-parse --short HEAD)"
echo ""

# Проверяем, что мы в git-репозитории
if ! git rev-parse --git-dir > /dev/null 2>&1; then
    echo "❌ Не найден git-репозиторий. Откат невозможен."
    exit 1
fi

# Запрос подтверждения
printf "Вы уверены, что хотите откатить последний коммит и принудительно запушить? [y/N] "
read -r answer
case "$answer" in
    [Yy]*)
        ;;
    *)
        echo "❌ Откат отменён."
        exit 0
        ;;
esac

# Откат
echo "🔄 Откатываемся на один коммит назад..."
git reset --hard HEAD~1

echo "🚀 Принудительно пушим изменения..."
git push --force

echo "✅ Откат выполнен. Render автоматически пересоберёт образ при следующем деплое."
